// Generates one docs page per community template (src/content/docs/templates/*.mdx) from the
// .keyly files in the keyly repo. Cloudflare only builds this repo, so the output is committed.
// Usage: node scripts/sync-templates.mjs [templates dir, default ../keyly/templates]
import { readdir, readFile, rm, mkdir, writeFile } from 'node:fs/promises';
import { join, resolve, basename } from 'node:path';

const sourceDir = resolve(process.argv[2] ?? '../keyly/templates');
const outDir = resolve('src/content/docs/templates');
const REPO = 'https://github.com/hoaiphongdev/keyly';
const INSTALL = 'curl -fsSL https://raw.githubusercontent.com/hoaiphongdev/keyly/main/scripts/install-templates.sh | bash -s -- -t';
const HEADER = '{/* Generated by scripts/sync-templates.mjs from the keyly repo templates — do not edit */}';

/** Mirrors ShortcutLineParser.split in the app: `|` first, then a tab or 2+ spaces, then the first space. */
function splitLine(line) {
	const nonEmpty = (a, b) => (a.trim() && b.trim() ? [a.trim(), b.trim()] : null);
	if (line.includes('|')) {
		const parts = line.split('|');
		const pair = parts.length === 2 && nonEmpty(parts[0], parts[1]);
		if (pair) return pair;
	}
	const sep = line.match(/\t|\s{2,}/) ?? line.match(/ /);
	return sep ? nonEmpty(line.slice(0, sep.index), line.slice(sep.index + sep[0].length)) : null;
}

/** Mirrors ConfigManager's .keyly parsing: headers, [categories], > hints, and every other `#` line skipped. */
function parseTemplate(content) {
	const sheet = { name: '', appPath: '', sections: [] };
	let section;
	for (const raw of content.split(/\r?\n/)) {
		const line = raw.trim();
		if (!line) continue;
		if (line.startsWith('# Sheet Name:')) sheet.name = line.slice('# Sheet Name:'.length).trim();
		else if (line.startsWith('# App:')) sheet.appPath = line.slice('# App:'.length).trim();
		else if (line.startsWith('#')) continue;
		else if (line.startsWith('[') && line.endsWith(']')) {
			section = { title: line.slice(1, -1).trim(), hints: [], rows: [] };
			sheet.sections.push(section);
		} else if (line.startsWith('>')) section?.hints.push(line.slice(1).trim());
		else {
			const pair = splitLine(line);
			if (!pair) continue;
			if (!section) {
				section = { title: 'General', hints: [], rows: [] };
				sheet.sections.push(section);
			}
			section.rows.push(pair);
		}
	}
	return sheet;
}

const escapeText = (text) => text.replace(/[\\`*_{}[\]<>|~]/g, '\\$&');

function inlineCode(text) {
	const longest = Math.max(0, ...(text.match(/`+/g) ?? []).map((run) => run.length));
	const fence = '`'.repeat(longest + 1);
	const padded = text.startsWith('`') || text.endsWith('`') ? ` ${text} ` : text;
	return `${fence}${padded.replace(/\|/g, '\\|')}${fence}`;
}

const yamlString = (text) => JSON.stringify(text);
const appName = ({ sheet }) => sheet.name.replace(/\s+Shortcuts$/i, '');

function renderPage(slug, sheet, raw, order) {
	const app = appName({ sheet });
	const count = sheet.sections.reduce((sum, s) => sum + s.rows.length, 0);
	// Some templates bind ``` itself, so the code fence must be longer than any backtick run in the file
	const rawFence = '`'.repeat(Math.max(3, ...(raw.match(/`+/g) ?? []).map((run) => run.length + 1)));
	const lines = [
		'---',
		`title: ${yamlString(`${app} Keyboard Shortcuts on Mac - Keyly Template`)}`,
		`description: ${yamlString(`All ${count} ${app} keyboard shortcuts for macOS in one overlay. Install the free Keyly template with one command and double-tap ⇪ Caps Lock to see them.`)}`,
		'sidebar:',
		`  label: ${yamlString(app)}`,
		`  order: ${order}`,
		'---',
		'',
		HEADER,
		'',
		`This page lists ${count} ${escapeText(app)} keyboard shortcuts for macOS, grouped by area. They come from the community \`${slug}.keyly\` template for [Keyly](/), a free, open-source menu bar app: install the template once, then double-tap \`⇪ Caps Lock\` in ${escapeText(app)} to see them next to the shortcuts Keyly reads from the app's menus.`,
		'',
		'## Install the template',
		'',
		'```bash',
		`${INSTALL} ${slug}.keyly`,
		'```',
		'',
		`This saves the template to \`~/.config/keyly/templates/${slug}.keyly\`. It targets \`${sheet.appPath}\`; if ${escapeText(app)} lives elsewhere on your Mac, [update the app path](/configuration/templates/). New to Keyly? Start with [Getting Started](/getting-started/).`,
		'',
	];
	for (const section of sheet.sections) {
		if (!section.rows.length) continue;
		lines.push(`## ${escapeText(section.title)}`, '');
		for (const hint of section.hints) lines.push(`${escapeText(hint)}`, '');
		lines.push('| Shortcut | Action |', '| --- | --- |');
		for (const [keys, action] of section.rows) lines.push(`| ${inlineCode(keys)} | ${escapeText(action)} |`);
		lines.push('');
	}
	lines.push(
		'## Template file',
		'',
		`The full [\`${slug}.keyly\`](${REPO}/blob/main/templates/${slug}.keyly) file. Copy it into \`~/.config/keyly/templates/\` to edit it, or [write your own](/configuration/custom-shortcuts/).`,
		'',
		'<details>',
		`<summary>Show ${slug}.keyly</summary>`,
		'',
		`${rawFence}keyly`,
		raw.trimEnd(),
		rawFence,
		'',
		'</details>',
		''
	);
	return { app, count, mdx: lines.join('\n') };
}

function renderIndex(pages) {
	const total = pages.reduce((sum, p) => sum + p.count, 0).toLocaleString('en-US');
	return [
		'---',
		`title: ${yamlString('Keyboard Shortcut Templates for macOS Apps')}`,
		`description: ${yamlString(`Free Keyly templates with ${total} keyboard shortcuts for ${pages.length} macOS apps, from Cursor and VS Code to Figma and Photoshop. Install one with a single command.`)}`,
		'sidebar:',
		`  label: ${yamlString('All templates')}`,
		'  order: 0',
		'---',
		'',
		HEADER,
		'',
		`Keyly reads shortcuts from each app's menus, but many apps also have shortcuts that never appear in a menu. Community templates fill that gap: ${pages.length} ready-made \`.keyly\` files with ${total} shortcuts in total. Pick an app to see every shortcut in its template and the one-line install command, or read [how templates work](/configuration/templates/).`,
		'',
		'| App | Shortcuts | Template |',
		'| --- | --- | --- |',
		...pages.map((p) => `| [${escapeText(p.app)}](/templates/${p.slug}/) | ${p.count} | \`${p.slug}.keyly\` |`),
		'',
	].join('\n');
}

const files = (await readdir(sourceDir)).filter((file) => file.endsWith('.keyly')).sort();
if (!files.length) throw new Error(`No .keyly templates in ${sourceDir}`);

await rm(outDir, { recursive: true, force: true });
await mkdir(outDir, { recursive: true });

const sheets = [];
for (const file of files) {
	const raw = await readFile(join(sourceDir, file), 'utf8');
	const sheet = parseTemplate(raw);
	if (!sheet.name) throw new Error(`${file} has no "# Sheet Name:" header`);
	sheets.push({ slug: basename(file, '.keyly'), sheet, raw });
}
// Sidebar order follows the app name, not the file name (acrobat.keyly is "Adobe Acrobat")
sheets.sort((a, b) => appName(a).localeCompare(appName(b)));

const pages = [];
for (const [i, { slug, sheet, raw }] of sheets.entries()) {
	const page = renderPage(slug, sheet, raw, i + 1);
	await writeFile(join(outDir, `${slug}.mdx`), page.mdx);
	pages.push({ slug, ...page });
}
await writeFile(join(outDir, 'index.mdx'), renderIndex(pages));

console.log(`✓ ${pages.length} template pages written to ${outDir}`);
